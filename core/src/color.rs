use crate::{Property, StyleError, StyleRule, Value, error};

pub(crate) fn parse(class: &str, offset: usize) -> Result<StyleRule, StyleError> {
    let Some(value) = class.strip_prefix("bg_") else {
        return Err(error(class, offset, "unknown style utility"));
    };

    let rgba = parse_value(value, class, offset)?;

    Ok(StyleRule {
        property: Property::BackgroundColor,
        value: Value::Background(rgba.0, rgba.1, rgba.2, rgba.3),
    })
}

pub(crate) fn parse_value(
    value: &str,
    class: &str,
    offset: usize,
) -> Result<(u8, u8, u8, u8), StyleError> {
    let rgba = match value {
        "transparent" => (0, 0, 0, 0),
        "black" => (0, 0, 0, 255),
        "white" => (255, 255, 255, 255),
        value if is_hex(value) => parse_hex(value, class, offset)?,
        value => {
            let (name, shade) = value
                .split_once('_')
                .map_or((value, "500"), |(name, shade)| (name, shade));
            let shade = shade.parse::<u16>().ok();
            let Some((red, green, blue)) = shade.and_then(|shade| palette(name, shade)) else {
                return Err(error(class, offset, "unknown background color"));
            };
            (red, green, blue, 255)
        }
    };

    Ok(rgba)
}

fn is_hex(value: &str) -> bool {
    (value.len() == 6 || value.len() == 8) && value.bytes().all(|byte| byte.is_ascii_hexdigit())
}

fn parse_hex(value: &str, class: &str, offset: usize) -> Result<(u8, u8, u8, u8), StyleError> {
    let parse = |part: &str| u8::from_str_radix(part, 16).ok();
    let Some(red) = parse(&value[0..2]) else {
        return Err(error(class, offset, "invalid background color"));
    };
    let Some(green) = parse(&value[2..4]) else {
        return Err(error(class, offset, "invalid background color"));
    };
    let Some(blue) = parse(&value[4..6]) else {
        return Err(error(class, offset, "invalid background color"));
    };
    let alpha = if value.len() == 8 {
        let Some(alpha) = parse(&value[6..8]) else {
            return Err(error(class, offset, "invalid background color"));
        };
        alpha
    } else {
        255
    };
    Ok((red, green, blue, alpha))
}

